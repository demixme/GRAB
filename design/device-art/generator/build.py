#!/usr/bin/env python3
"""GRAB device-art generator - flat illustration style.

Every device is drawn from (a) geometry that mirrors GRAB's src/gui/KeyboardView.h and the product
photos, and (b) the tokens in style.json. The style is one rule set applied everywhere:

  * one shared tone ladder: edge / deep / mid / base / lit / white - no gradients
  * light from the top-right at 45 degrees:
      raised parts  -> face + a 'deep' cast shadow offset down-left
      sunken wells  -> 'mid' floor + a 'deep' strip along the top and right inner walls
      bodies        -> 'base' + 'edge' outline + a 'lit' line on the top-right edge
      shadow bands  -> 'deep' core with a 'mid' penumbra on the soft side

Only JUCE-safe SVG is emitted (rect / circle / path / g; no filters, masks, CSS or <text>).

Run:  python3 generator/build.py      (then open art/preview.html)
"""
import json, math, os, re, sys
from contextlib import contextmanager

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "art")
S = json.load(open(os.path.join(HERE, "style.json")))
L = S["light"]


def f(v):
    if isinstance(v, float):
        s = f"{v:.2f}".rstrip("0").rstrip(".")
        return "0" if s in ("-0", "") else s
    return str(v)


def tones(family, part=None):
    """The shared ladder, optionally overridden per device part (e.g. the RISE's lighter body)."""
    t = {k: v for k, v in S["tones"].items() if not k.startswith("_")}
    if part:
        t.update(S["devices"][family].get(part, {}))
    return t


# --------------------------------------------------------------------------------------------
# Minimal SVG document builder
# --------------------------------------------------------------------------------------------
class Doc:
    def __init__(self, w, h, title, meta):
        self.w, self.h, self.title, self.meta = w, h, title, meta
        self.root = []
        self.stack = [self.root]
        self.ids = set()

    def _attrs(self, a):
        out = []
        for k, v in a.items():
            if v is None:
                continue
            out.append(f'{k.rstrip("_").replace("_", "-")}="{f(v)}"')
        return " ".join(out)

    def add(self, tag, **a):
        if a.get("id"):
            assert a["id"] not in self.ids, f"duplicate id {a['id']}"
            self.ids.add(a["id"])
        self.stack[-1].append(f"<{tag} {self._attrs(a)}/>")

    @contextmanager
    def g(self, id=None, **a):
        if id:
            assert id not in self.ids, f"duplicate id {id}"
            self.ids.add(id)
        kids = []
        self.stack.append(kids)
        yield
        self.stack.pop()
        attrs = self._attrs(dict(id=id, **a))
        self.stack[-1].append(f"<g {attrs}>" + "".join(kids) + "</g>")

    def svg(self):
        meta = " ".join(f'data-grab-{k}="{v}"' for k, v in self.meta.items())
        return (f'<?xml version="1.0" encoding="UTF-8"?>\n'
                f'<!-- Generated by GRAB-design/generator/build.py - edit style.json, not this file. -->\n'
                f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {self.w} {self.h}" '
                f'width="{self.w}" height="{self.h}" {meta}>\n'
                f'<title>{self.title}</title>\n' + "\n".join(self.root) + "\n</svg>\n")


# --------------------------------------------------------------------------------------------
# Shapes
# --------------------------------------------------------------------------------------------
def rr(d, x, y, w, h, r, **a):
    d.add("rect", x=x, y=y, width=w, height=h, rx=max(0, min(r, w / 2, h / 2)), **a)


def poly(pts, close=False):
    return "M" + "L".join(f"{f(x)} {f(y)}" for x, y in pts) + ("Z" if close else "")


def ring(cx, cy, ro, ri):
    def circ(r):
        return f"M{f(cx - r)} {f(cy)}a{f(r)} {f(r)} 0 1 0 {f(2 * r)} 0a{f(r)} {f(r)} 0 1 0 {f(-2 * r)} 0Z"
    return circ(ro) + (circ(ri) if ri > 0 else "")


def half_pill(x, y, w, h, side):
    r = h / 2
    if side == "left":
        return f"M{f(x + w)} {f(y)}L{f(x + r)} {f(y)}A{f(r)} {f(r)} 0 0 0 {f(x + r)} {f(y + h)}L{f(x + w)} {f(y + h)}Z"
    return f"M{f(x)} {f(y)}L{f(x + w - r)} {f(y)}A{f(r)} {f(r)} 0 0 1 {f(x + w - r)} {f(y + h)}L{f(x)} {f(y + h)}Z"


def half_pill_ring(x, y, w, h, side, grow, inner=0.0):
    o = half_pill(x - (grow if side == "left" else 0), y - grow, w + grow, h + 2 * grow, side)
    i = half_pill(x - (inner if side == "left" else 0), y - inner, w + inner, h + 2 * inner, side)
    return o + i


