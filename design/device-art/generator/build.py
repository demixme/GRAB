def arc_pts(cx, cy, rx, ry, a0, a1, n=24):
    """JUCE addCentredArc convention: angle 0 = 12 o'clock, clockwise."""
    return [(cx + rx * math.sin(a0 + (a1 - a0) * k / n), cy - ry * math.cos(a0 + (a1 - a0) * k / n)) for k in range(n + 1)]


