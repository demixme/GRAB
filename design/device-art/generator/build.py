def scale_path(p, ox, oy, k):
    out, axis, cmd = [], 0, ""
    for tok in re.findall(r"[MLHVCZ]|-?(?:\d+\.?\d*|\.\d+)", p):
        if tok.isalpha():
            cmd, axis = tok, 0
            out.append(tok)
            continue
        v = float(tok)
        if cmd == "H":
            out.append(f(ox + v * k))
        elif cmd == "V":
            out.append(f(oy + v * k))
        else:
            out.append(f((ox if axis == 0 else oy) + v * k)); axis ^= 1
    return " ".join(out).replace(" M", "M")


def unit_path(p, cx, cy, k):
    """Absolute M/L/H/V/C/A/Z path in button-radius units (centre 0,0) -> document coordinates."""
    out = []
    for cmd, args in re.findall(r"([MLHVCAZ])([^MLHVCAZ]*)", p):
        n = [float(v) for v in re.findall(r"-?(?:\d+\.?\d*|\.\d+)", args)]
        if cmd == "H": n = [cx + v * k for v in n]
        elif cmd == "V": n = [cy + v * k for v in n]
        elif cmd == "A":
            n = [v for i in range(0, len(n), 7) for v in (n[i] * k, n[i+1] * k, n[i+2], n[i+3], n[i+4], cx + n[i+5] * k, cy + n[i+6] * k)]
        else: n = [cx + v * k if i % 2 == 0 else cy + v * k for i, v in enumerate(n)]
        out.append(cmd + " ".join(f(v) if not float(v).is_integer() or abs(v) > 1 else str(int(v)) for v in n))
    return "".join(out)


def NOTES(*pts):
    """Live Block note glyph: a small ring on a short ledger line, one per point."""
    return "".join(f"M{x-.19:.3f} {y:.3f}H{x-.08:.3f}M{x+.08:.3f} {y:.3f}H{x+.19:.3f}"
                   f"M{x:.3f} {y-.08:.3f}A.08 .08 0 1 1 {x:.3f} {y+.08:.3f}A.08 .08 0 1 1 {x:.3f} {y-.08:.3f}Z" for x, y in pts)


