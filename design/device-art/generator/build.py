# RISE control panel (measured from the RISE 25 / RISE 2 top views; both share this layout)
# --------------------------------------------------------------------------------------------
def rise_panel(d, t):
    P = dict(nav=(68, 30, 53, 19), faders=[(33, 64), (67, 64), (100, 64)], fw=21.5, fh=84.5,
             xy=(33, 162, 88, 68), mode=(44, 253, 9.6), oct=(68, 243.5, 53, 18.5))
    glyph = dict(fill="none", stroke=t["white"], stroke_opacity=0.7, stroke_width=0.9, stroke_linecap="round", stroke_linejoin="round")
    with d.g("panel"):
        pass
    with d.g("fader-tracks"):
        for i, (x, y) in enumerate(P["faders"]):
            with d.g(f"fader-track-{i}"):
                rr(d, x - 0.8, y - 0.8, P["fw"] + 1.6, P["fh"] + 1.6, 5, fill=t["edge"])
                well(d, x, y, P["fw"], P["fh"], 4, t)
                lw = t.get("faderLineW", 1.2)
                rr(d, x + P["fw"] / 2 - lw / 2, y + 18, lw, P["fh"] - t.get("faderLineEnd", 26), lw / 2,
                   fill=t.get("faderLine", t["white"]), fill_opacity=t.get("faderLineOpacity", 0.35))
    with d.g("xy-pad"):
        x, y, w, h = P["xy"]
        with d.g("xy-surface"):
            rr(d, x - 0.8, y - 0.8, w + 1.6, h + 1.6, 6, fill=t["edge"])
            well(d, x, y, w, h, 5, t)
        cx, cy, a = x + w / 2, y + h / 2, 2.2
        for dx, dy in ((0, -h * 0.36), (0, h * 0.36), (-w * 0.38, 0), (w * 0.38, 0)):
            px, py = cx + dx, cy + dy
            nx, ny = (dx > 0) - (dx < 0), (dy > 0) - (dy < 0)
            d.add("path", d=poly([(px - nx * a - ny * a, py - ny * a + nx * a), (px, py), (px - nx * a + ny * a, py - ny * a - nx * a)]), **glyph)
        d.add("circle", cx=cx, cy=cy, r=1, fill=t["white"], fill_opacity=0.7)

    (nx_, ny_, nw, nh), (ox_, oy_, ow, oh), (mx, my, mr) = P["nav"], P["oct"], P["mode"]
    with d.g("buttons"):
        for (x, y, w, h), ids in (((nx_, ny_, nw, nh), ("btn-nav-prev", "btn-nav-next")),
                                  ((ox_, oy_, ow, oh), ("btn-oct-down", "btn-oct-up"))):
            rr(d, x - L["cast"] - 0.8, y + L["cast"] - 0.8, w + 1.6, h + 1.6, h / 2 + 0.8, fill=t["deep"])
            rr(d, x - 0.8, y - 0.8, w + 1.6, h + 1.6, h / 2 + 0.8, fill=t["edge"])
            d.add("path", id=ids[0], d=half_pill(x, y, w / 2, h, "left"), fill=t["mid"])
            d.add("path", id=ids[1], d=half_pill(x + w / 2, y, w / 2, h, "right"), fill=t["mid"])
            rr(d, x + w / 2 - 0.4, y + 3, 0.8, h - 6, 0.4, fill=t["edge"])
        d.add("circle", cx=mx - L["cast"], cy=my + L["cast"], r=mr + 0.8, fill=t["deep"])
        d.add("circle", cx=mx, cy=my, r=mr + 0.8, fill=t["edge"])
        d.add("circle", id="btn-mode", cx=mx, cy=my, r=mr, fill=t["mid"])
    with d.g("button-leds"):
        with d.g("btnled-mode"):
            led_glow(d, lambda g, i: ring(mx, my, mr + 0.8 + g, mr + 0.8))
        with d.g("btnled-oct-down"):
            led_glow(d, lambda g, i: half_pill_ring(ox_, oy_, ow / 2, oh, "left", g + 0.8, 0.8))
        with d.g("btnled-oct-up"):
            led_glow(d, lambda g, i: half_pill_ring(ox_ + ow / 2, oy_, ow / 2, oh, "right", g + 0.8, 0.8))
    with d.g("labels"):
        cy = ny_ + nh / 2
        for gx, dirn in ((nx_ + nw * 0.25, -1), (nx_ + nw * 0.75, 1)):
            d.add("path", d=chevron_path(gx, cy, 2, dirn), **glyph)
        cy = oy_ + oh / 2
        d.add("path", d=f"M{f(ox_ + ow*0.25 - 2)} {f(cy)}H{f(ox_ + ow*0.25 + 2)}", **glyph)
        d.add("path", d=f"M{f(ox_ + ow*0.75 - 2)} {f(cy)}H{f(ox_ + ow*0.75 + 2)}M{f(ox_ + ow*0.75)} {f(cy - 2)}V{f(cy + 2)}", **glyph)
        d.add("circle", cx=mx, cy=my, r=1.1, fill=t["white"], fill_opacity=0.8)
        for i, (x, y) in enumerate(P["faders"]):          # fader head glyphs: <>, ^v, dot
            cx, gy = x + P["fw"] / 2, y + 8
            if i == 0:
                d.add("path", d=chevron_path(cx - 1.6, gy, 1.6, -1) + chevron_path(cx + 1.6, gy, 1.6, 1), **glyph)
            elif i == 1:
                d.add("path", d=f"M{f(cx-1.6)} {f(gy-1)}L{f(cx)} {f(gy-2.6)}L{f(cx+1.6)} {f(gy-1)}M{f(cx-1.6)} {f(gy+1)}L{f(cx)} {f(gy+2.6)}L{f(cx+1.6)} {f(gy+1)}", **glyph)
            else:
                d.add("circle", cx=cx, cy=gy, r=1.2, fill=t["white"], fill_opacity=0.7)
    with d.g("panel-live"):
        x, y, w, h = P["xy"]
        with d.g("xy-dot"):
            d.add("circle", cx=x + w / 2, cy=y + h / 2, r=5, fill="#0be4f4", fill_opacity=0.2)
            d.add("circle", cx=x + w / 2, cy=y + h / 2, r=2.6, fill="#0be4f4")
        for i, (fx, fy) in enumerate(P["faders"]):
            cx, ty = fx + P["fw"] / 2, fy + P["fh"] * 0.6
            with d.g(f"fader-thumb-{i}"):
                rr(d, cx - 4.5, ty - 1.2, 9, 2.4, 1.2, fill=t["white"])


