# The light rules
# --------------------------------------------------------------------------------------------
def body(d, x, y, w, h, r, t):
    """Shell: base tone, edge outline, lit line where the top-right light catches the rim."""
    rr(d, x, y, w, h, r, fill=t["base"], stroke=t["edge"], stroke_width=1)
    d.add("path", d=f"M{f(x + w * 0.35)} {f(y + 1)}H{f(x + w - r)}A{f(r - 1)} {f(r - 1)} 0 0 1 {f(x + w - 1)} {f(y + r)}V{f(y + h * 0.45)}",
          fill="none", stroke=t["lit"], stroke_width=1, stroke_linecap="round")


def well(d, x, y, w, h, r, t, floor="mid", inset=None):
    """Sunken area: deep strip along the top and right inner walls (they shade the floor)."""
    k = L["inset"] if inset is None else inset
    rr(d, x, y, w, h, r, fill=t["deep"])
    rr(d, x, y + k, w - k, h - k, max(0, r - k / 2), fill=t[floor])


def raised_rr(d, x, y, w, h, r, face, t, cast=None, **a):
    """Raised rounded rect: deep shadow thrown down-left, then the face."""
    c = L["cast"] if cast is None else cast
    rr(d, x - c, y + c, w, h, r, fill=t["deep"])
    rr(d, x, y, w, h, r, fill=face, **a)


def raised_circle(d, cx, cy, r, face, t, cast=None, **a):
    c = L["cast"] if cast is None else cast
    d.add("circle", cx=cx - c, cy=cy + c, r=r, fill=t["deep"])
    d.add("circle", cx=cx, cy=cy, r=r, fill=face, **a)


def finish(d, r):
    sf = S["selectionFrame"]
    rr(d, 1.5, 1.5, d.w - 3, d.h - 3, r + 1.5, id="selection-frame", fill="none", stroke=S["accent"],
       stroke_width=sf["width"], stroke_opacity=sf["opacity"] if sf["show"] else 0)
    with d.g("live-overlay"):
        pass


# --------------------------------------------------------------------------------------------
# LEDs: flat translucent rings/dots of one colour - GRAB recolours them, keeping each alpha
# --------------------------------------------------------------------------------------------
LED_DEFAULT = "#00B0BB"


def led_glow(d, shape, colour=LED_DEFAULT):
    for grow, op in ((3.4, 0.16), (1.6, 0.95)):
        d.add("path", d=shape(grow, 0.0), fill=colour, fill_opacity=op, fill_rule="evenodd")


def led_dot(d, id, cx, cy, r, colour, lit):
    with d.g(id, opacity=1 if lit else 0.3):
        d.add("circle", cx=cx, cy=cy, r=r * 2.2, fill=colour, fill_opacity=0.18 if lit else 0)
        d.add("circle", cx=cx, cy=cy, r=r, fill=colour)


# --------------------------------------------------------------------------------------------
# Keyboard maths - identical to KeyboardView.h
# --------------------------------------------------------------------------------------------
WHITE_PC = {0, 2, 4, 5, 7, 9, 11}


def key_layout(low, count):
    """[('w'|'b', index_within_colour, whites_before)], total whites."""
    wc, wi, bi, out = 0, 0, 0, []
    for s in range(count):
        if (low + s) % 12 in WHITE_PC:
            out.append(("w", wi, wc)); wi += 1; wc += 1
        else:
            out.append(("b", bi, wc)); bi += 1
    return out, wc


# --------------------------------------------------------------------------------------------
# Seaboard keywave (Block / RISE / GRAND)
# --------------------------------------------------------------------------------------------
def keywave(d, x0, y0, W, H, low, count, family, black="ridge"):
    """Flat keywave in the region x0..x0+W, y0..y0+H.

    Each white key's shadowed left flank is a deep band with a mid penumbra on its soft side.
    Where a black key sits on the boundary, the band runs down the black key's left side then
    jogs right below it (the Seaboard S-step). Black keys are the lit ridges; the white crest line
    sits exactly on the boundary between the two white keys."""
    t = tones(family)
    K = dict(S["keywave"]); K.update(S["devices"][family].get("keywave", {}))
    keys, whites = key_layout(low, count)
    ww = W / whites
    Y = lambda fr: y0 + fr * H
    top, step, bot = Y(K["railTop"]), Y(K["step"]), Y(K["railBottom"])
    bw, band, pen = ww * K["blackW"], ww * K["band"], ww * K["penumbra"]
    blacks_at = {wc for kind, _, wc in keys if kind == "b"}

    with d.g("surface"):
        pass                                          # rails are the surface the keys sit in
    with d.g("keys-white"):
        for kind, i, wc in keys:
            if kind == "w":
                d.add("rect", id=f"w-{i}", x=x0 + wc * ww, y=top, width=ww, height=bot - top, fill=t["base"])
    with d.g("shading"):
        for wc in range(whites):
            b = x0 + wc * ww                          # left edge of this white key
            if wc in blacks_at:
                hw = bw / 2 if black == "ridge" else bw * 0.5
                x1, x2 = b - hw - band, b - hw        # upper band, left of the black key
                x3, x4 = b, b + band                  # lower band, the key's own left flank
                jog = (x3 - x1) * K["jog"]
                core = [(x1, top), (x2, top), (x2, step), (x4, step + jog), (x4, bot), (x3, bot), (x3, step + jog), (x1, step)]
                soft = [(x1 - pen, top), (x2, top), (x2, step), (x4 + pen, step + jog), (x4 + pen, bot), (x3, bot), (x3, step + jog), (x1 - pen, step)]
                d.add("path", d=poly(soft, True), fill=t["mid"])
                d.add("path", d=poly(core, True), fill=t["deep"])
            elif wc > 0:
                x = b - band * 0.25
                d.add("rect", x=x, y=top, width=band + pen, height=bot - top, fill=t["mid"])
                d.add("rect", x=x, y=top, width=band, height=bot - top, fill=t["deep"])
    with d.g("keys-black"):
        for kind, i, wc in keys:
            if kind != "b":
                continue
            cx = x0 + wc * ww
            if black == "pill":                       # GRAND: pale raised pills
                pw = bw * 0.82
                raised_rr(d, cx - pw / 2, top + 2, pw, step - top - 2, pw / 2, S["devices"][family]["pill"], t, id=f"b-{i}")
                continue
            d.add("rect", id=f"b-{i}", x=cx - bw / 2, y=top, width=bw, height=step - top, fill=t["lit"])
            ly0, ly1 = top + (step - top) * 0.22, top + (step - top) * 0.93
            rr(d, cx - 0.8, ly0, 1.6, ly1 - ly0, 0.8, fill=t["white"])


def chevron_path(cx, cy, s, dirn):
    return f"M{f(cx - dirn * s * 0.5)} {f(cy - s)}L{f(cx + dirn * s * 0.5)} {f(cy)}L{f(cx - dirn * s * 0.5)} {f(cy + s)}"


def seaboard_block(W=600, H=300, low=48, count=24):
    t = tones("block")
    r = S["devices"]["block"]["bodyRadius"]
    # Keys span r.reduced(3, 4) exactly like KeyboardView, so touch mapping is unchanged.
    d = Doc(W, H, "Seaboard Block", {"family": "block", "footprint": f"{W/100:g}x{H/100:g}",
                                     "active-area": f"3 4 {W - 6} {H - 8}", "keys": f"{low} {count}"})
    with d.g("chassis"):
        body(d, 3, 3, W - 6, H - 6, r, t)
    with d.g("labels"):
        gy = 3 + (H - 6) * 0.07
        for gx, dirn in ((16, -1), (W - 16, 1)):
            d.add("path", d=chevron_path(gx, gy, 3.2, dirn), fill="none", stroke=t["white"], stroke_opacity=0.5,
                  stroke_width=0.9, stroke_linecap="round", stroke_linejoin="round")
    keywave(d, 3, 3, W - 6, H - 6, low, count, "block")
    finish(d, r)
    return d


def tray_device(name, family, W, H, low, count, tray, *, panel=False, top_button=False):
    """RISE / GRAND: a body with the keywave sunk into a tray."""
    tb, tk = tones(family, "body"), tones(family)
    r = S["devices"][family]["bodyRadius"]
    tx, ty, tw, th = tray
    kx, ky, kw, kh = tx + 2, ty + 2, tw - 4, th - 4
    d = Doc(W, H, name, {"family": family, "footprint": f"{W/100:g}x{H/100:g}",
                         "active-area": f"{f(kx)} {f(ky)} {f(kw)} {f(kh)}", "keys": f"{low} {count}"})
    with d.g("chassis"):
        body(d, 3, 3, W - 6, H - 6, r, tb)
        rr(d, tx - 1, ty - 1, tw + 2, th + 2, 6, fill=tb["edge"])
        well(d, tx, ty, tw, th, 5, tk, floor="base")
        if top_button:                                   # GRAND: round master button in the top bezel
            cx, cy, rb = W / 2, ty / 2 + 2, ty * 0.3
            d.add("circle", cx=cx, cy=cy, r=rb + 1, fill=tb["edge"])
            raised_circle(d, cx, cy, rb, tb["lit"], tb)
            d.add("circle", cx=cx, cy=cy, r=rb * 0.42, fill=tb["mid"], stroke=tb["deep"], stroke_width=0.8)
    if panel:
        rise_panel(d, tb)
    keywave(d, kx, ky, kw, kh, low, count, family, "pill" if family == "grand" else "ridge")
    finish(d, r)
    return d


